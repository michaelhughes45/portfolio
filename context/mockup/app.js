// Theme toggle (remembered per browser)
function initTheme() {
  const root = document.documentElement;
  try { const t = localStorage.getItem("theme"); if (t) root.dataset.theme = t; } catch {}
  const forced = new URLSearchParams(location.search).get("theme"); // ?theme=dark|light, used for screenshots
  if (forced === "dark" || forced === "light") root.dataset.theme = forced;
  const btn = document.getElementById("theme");
  if (!btn) return;
  const isDark = () => root.dataset.theme ? root.dataset.theme === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;
  const paint = () => (btn.innerHTML = icon(isDark() ? "sun" : "moon"));
  paint();
  btn.addEventListener("click", () => {
    root.dataset.theme = isDark() ? "light" : "dark";
    try { localStorage.setItem("theme", root.dataset.theme); } catch {}
    paint();
  });
}

// Browser frame that shows the live site, scaled down from a 1280px desktop view.
// The real site will use screenshots instead; this is just to preview with real content.
function frame(p) {
  const host = new URL(p.live).host;
  return `<div class="frame" style="--accent:${p.accent};--accent2:${p.accent2}">
    <div class="frame-bar"><span class="dot"></span><span class="dot"></span><span class="dot"></span><span class="frame-url">${host}</span></div>
    <div class="frame-view"><div class="frame-fallback"><div>${p.name}<small>screenshot goes here</small></div></div>
      ${p.embed === false ? "" : `<iframe src="${p.live}" loading="lazy" tabindex="-1" aria-hidden="true" title="${p.name} preview"></iframe>`}</div>
  </div>`;
}
function fitFrames() {
  const ro = new ResizeObserver((entries) => {
    for (const e of entries) {
      const view = e.target, f = view.querySelector("iframe");
      if (!f) continue;
      const s = view.clientWidth / 1280;
      f.style.width = "1280px";
      f.style.height = view.clientHeight / s + "px";
      f.style.transform = `scale(${s})`;
    }
  });
  document.querySelectorAll(".frame-view").forEach((v) => ro.observe(v));
}

function initReveal() {
  const io = new IntersectionObserver((es) => es.forEach((e) => e.isIntersecting && (e.target.classList.add("in"), io.unobserve(e.target))), { threshold: 0.12 });
  document.querySelectorAll(".reveal").forEach((el) => io.observe(el));
}

// Site nav: Home, a Projects menu linking each project page, About.
function renderNav(active) {
  const nav = document.querySelector(".nav-links");
  if (!nav) return;
  nav.innerHTML = `
    <a href="index.html" class="hide-sm">Home</a>
    <div class="nav-drop">
      <button type="button" aria-haspopup="true">Projects ${icon("arrow")}</button>
      <div class="nav-menu">${PROJECTS.map((p) => `
        <a href="project.html?p=${p.slug}" class="${p.slug === active ? "active" : ""}" style="--accent:${p.accent};--accent2:${p.accent2}">
          <span class="sw"></span><span><b>${p.name}</b><small>${p.type}</small></span></a>`).join("")}
      </div>
    </div>
    <a href="index.html#about" class="hide-sm">About</a>`;
}

function hydrateIcons() {
  document.querySelectorAll("[data-icon]").forEach((el) => el.insertAdjacentHTML("afterbegin", icon(el.dataset.icon)));
}
